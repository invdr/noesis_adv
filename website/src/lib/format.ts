// Презентационный хелпер лендинга, специфичный для сайта. Общие форматтеры
// (комнатность, цена, абзацы новости) берём из @gsk-tower/contracts — единый
// источник, чтобы не плодить копии. На клиент эти модули не уходят: используются
// только во фронтматтере страниц на этапе сборки (zod в бандл не попадает).

const MONTHS_GENITIVE = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
];

/**
 * ISO-дата → «12 марта 2026» (как в исходном дизайне). Берём UTC-компоненты:
 * дата сидится на полночь UTC, без сдвига по часовому поясу сборщика.
 */
export function formatNewsDate(iso: string): string {
  const d = new Date(iso);
  return `${d.getUTCDate()} ${MONTHS_GENITIVE[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
}
