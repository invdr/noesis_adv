/**
 * Цифровой терм для поиска по телефону: выдёргивает цифры из ввода, ведущую
 * `8` приводит к `7` (хранение — `+7…`). Меньше 3 цифр — не телефонный запрос,
 * возвращаем `null` (иначе однозначный «1» матчил бы полбазы).
 *
 * Живёт здесь, а не в фиче: правило одинаково применяют поиск по заявкам и
 * поиск по контрагентам — это одно и то же пользовательское поведение на двух
 * списках CRM. Раньше у каждого сервиса была своя копия, и разъехаться они
 * могли молча. Импортировать из соседней фичи нельзя: `lead-service` уже
 * зависит от `contact-service`, обратный импорт замкнул бы цикл.
 *
 * Не путать с `normalizeRuPhone` из контрактов — та приводит номер к
 * каноническому виду для ХРАНЕНИЯ, а эта готовит подстроку для поиска.
 */
export function normalizePhoneSearch(term: string): string | null {
  const digits = term.replace(/\D/g, "");
  if (digits.length < 3) return null;
  return digits.replace(/^8/, "7");
}
