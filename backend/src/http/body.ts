import type { Context } from "hono";
import { HttpError } from "./errors";

/**
 * Читает JSON-тело запроса.
 *
 * Почему не `await c.req.json().catch(() => ({}))`, как в части старых роутов:
 * такая подмена превращает нечитаемое тело в пустой объект и отдаёт его схеме.
 * Это безопасно ровно до тех пор, пока схема отвергает `{}`. Стоит появиться
 * схеме, у которой все поля необязательные (например,
 * `updateSiteSettingsSchema`), — и битое тело проходит валидацию как «ничего не
 * менять», а хендлер, который пишет полный снимок, затирает данные и отвечает
 * 200 OK. Именно так и произошло с настройками сайта.
 *
 * Поэтому отсутствующее или неразбираемое тело — это отдельная ошибка запроса
 * (400), а не пустой ввод формы (422 с разбором по полям).
 */
export async function readJsonBody(c: Context): Promise<unknown> {
  try {
    return await c.req.json();
  } catch {
    throw new HttpError(
      400,
      "invalid_json",
      "Тело запроса отсутствует или не является корректным JSON",
    );
  }
}
